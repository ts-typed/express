import type { ErrorRequestHandler, Request } from 'express';
import {
  StrictTypeError,
  type StrictTypeErrorInfo,
} from '@ts-typed/compiler';

const SERVER_FAULT_OPERATIONS: ReadonlySet<string> = new Set(['return', 'resolve']);
const SERVER_FAULT_CONTRACT_KINDS: ReadonlySet<string> = new Set(['variable']);

export interface TypedErrorResponse extends StrictTypeErrorInfo {
  readonly statusCode: number;
  readonly message: string;
  readonly errors?: readonly StrictTypeErrorInfo[];
}

export interface TypedErrorHandlerOptions {
  /** Called after a StrictTypeError is recognized, before the response is sent. */
  readonly onError?: (error: StrictTypeError, request: Request) => void;
  /** Allows an application to wrap or replace the safe response body. */
  readonly formatResponse?: (
    body: TypedErrorResponse,
    error: StrictTypeError,
    request: Request,
  ) => unknown;
}

function resolveStatus(error: StrictTypeError): number {
  if (error.typeErrorResponseStatus !== undefined) {
    return error.typeErrorResponseStatus;
  }
  if (error.typeErrorResponseMessage !== undefined) {
    return 400;
  }

  const serverFault =
    SERVER_FAULT_OPERATIONS.has(error.operation) ||
    SERVER_FAULT_CONTRACT_KINDS.has(error.contractKind) ||
    error.isServerPopulated === true;

  return serverFault ? 500 : 400;
}

/** Converts a compiler error into the safe HTTP body used by the Express handler. */
export function toTypedErrorResponse(error: StrictTypeError): TypedErrorResponse {
  return {
    statusCode: resolveStatus(error),
    message: error.typeErrorResponseMessage ?? error.message,
    ...error.toJSON(),
  };
}

/**
 * Express error middleware for runtime contracts generated by ts-typed.
 * Register it after application routes and before any fallback error handler.
 */
export function typedErrorHandler(options: TypedErrorHandlerOptions = {}): ErrorRequestHandler {
  return (error, request, response, next): void => {
    if (!(error instanceof StrictTypeError)) {
      next(error);
      return;
    }
    // A response already in flight (headers written by a route before it
    // threw) cannot be restarted with .status()/.json() — that throws
    // ERR_HTTP_HEADERS_SENT. Hand the error to whatever comes next instead.
    if (response.headersSent) {
      next(error);
      return;
    }

    try {
      options.onError?.(error, request);
    } catch {
      // A logging/telemetry hook failing must not cost the client its safe
      // typed response.
    }
    const body = toTypedErrorResponse(error);
    let payload: unknown = body;
    if (options.formatResponse !== undefined) {
      try {
        payload = options.formatResponse(body, error, request) ?? body;
      } catch {
        payload = body;
      }
    }
    response.status(body.statusCode).json(payload);
  };
}

export type { StrictTypeErrorInfo } from '@ts-typed/compiler';
